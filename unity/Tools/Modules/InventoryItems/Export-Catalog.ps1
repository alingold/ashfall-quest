param([string]$Root='C:/Users/aling/Documents/ashfall')
$ErrorActionPreference='Stop'
$source=Join-Path $Root 'quest-r22/source'
$rack=Get-Content "$source/scripts/weapon_rack.gd" -Raw
function ReadArray($pattern) {
 $match=[regex]::Match($rack,$pattern)
 if(!$match.Success){throw "Rack declaration missing: $pattern"}
 return @($match.Groups[1].Value | ConvertFrom-Json)
}
$ids=ReadArray 'var weapon_ids:Array\[String\]=([^\r\n]+)'
$names=ReadArray 'var weapon_names:Array\[String\]=([^\r\n]+)'
$families=ReadArray 'const AMMO_FAMILIES:Array\[String\]=([^\r\n]+)'
$active=ReadArray 'const ACTIVE_WEAPON_INDICES:Array\[int\]=([^\r\n]+)'
$profiles=(Get-Content "$source/assets/data/one_star_050.json" -Raw|ConvertFrom-Json).profiles
$rarity=(Get-Content "$source/assets/data/weapon_rarity_r6.json" -Raw|ConvertFrom-Json).weapons
$gray=(Get-Content "$source/assets/data/one_star0991.json" -Raw|ConvertFrom-Json).weapons
function Num($value) { return ([double]$value).ToString('R',[Globalization.CultureInfo]::InvariantCulture) }
function Quote($value) { return '"'+([string]$value).Replace('\','\\').Replace('"','\"')+'"' }
$lines=New-Object 'System.Collections.Generic.List[string]'
$lines.Add('// Generated by Tools/Modules/InventoryItems/Export-Catalog.ps1; do not hand-edit.')
$lines.Add('namespace Ashfall.Modules.InventoryItems { public static class SourceCatalog { public static ItemCatalog Create() { return new ItemCatalog(new ItemDefinition[] {')
$records=@()
for($i=0;$i -lt 30;$i++) {
 $p=$profiles|Where-Object { $_.index -eq $i }; $r=$rarity.PSObject.Properties[[string]$p.id].Value
 $g=$gray.PSObject.Properties[[string]$p.id].Value
 $category=6
 if($i -in 14,15,16,29){$category=0} elseif($i -in 1,4,9,12){$category=1} elseif($i -in 2,7,19,20){$category=2} elseif($i -in 6,10,11,17,18){$category=3} elseif($i -in 0,3,8,21,23,24){$category=4} elseif($i -in 5,13,25){$category=5}
 $tiered=$i -notin 14,15,16,26,28,29; $isActive=$i -in $active
 $hands=1; if($i -in 11,12){$hands=2}
 $rate=[double]$p.rounds_per_second; if($i -eq 12){$rate*=1.2}
 $levels=@()
 for($star=0;$star -lt 5;$star++) {
  $body=0; $head=0; $pellets=1; $mag=[int]$p.magazine_per_hand; $recoil=1; $spread=1
  if($i -in 26,28){$mag=1}
  if($g){$body=$g.body;$head=$g.head;$pellets=$g.pellets}
  if($r){$body=$r.body[$star];$head=$r.head[$star];$pellets=$r.pellets;$mag=$r.magazine[$star];$recoil=$r.recoil[$star];$spread=$r.spread[$star]}
  # Melee damage is speed-dependent in Combat; zero here means no firearm damage row.
  $levels+='new WeaponStats('+((@($body,$head,$pellets,$mag,$hands,$recoil,$spread)|ForEach-Object {Num $_}) -join ',')+')'
 }
 $stack='';if($i -eq 26){$stack='frag'}
 $args=@((Quote $ids[$i]),(Quote $p.id),(Quote $names[$i]),$i,$isActive.ToString().ToLower(),$category,(Quote $families[$i]),(Quote $p.fire_mode),(Num $rate),$tiered.ToString().ToLower(),(Quote $stack))
 $lines.Add('new ItemDefinition('+($args -join ',')+',new WeaponStats[]{'+($levels -join ',')+'}),')
 $records+=@{index=$i;id=$ids[$i];profileId=$p.id;active=$isActive;ammoFamily=$families[$i];rate=$rate;category=$category;stackKey=$stack}
}
foreach($kind in 'shaker','soda','banana','backpack','revive') {
 $stack=if($kind -in 'shaker','soda'){$kind}else{''}
 $titles=@{shaker='SHIELD SHAKER';soda='SHIELD SODA';banana='BANANA';backpack='BACKPACK +1 SLOT';revive='REVIVE PADDLES'}
 $lines.Add('new ItemDefinition("'+$kind+'","","'+$titles[$kind]+'",-1,true,7,"","",0,false,"'+$stack+'",new WeaponStats[]{'+((1..5|ForEach-Object {'new WeaponStats(0,0,1,0,1,1,1)'}) -join ',')+'}),')
}
$lines.Add('}); } } }')
$output=Join-Path $Root 'unity/Assets/Ashfall/Modules/InventoryItems/SourceCatalog.cs'
[IO.File]::WriteAllLines($output,$lines,(New-Object Text.UTF8Encoding($false)))
$evidence=Join-Path $Root 'docs/agent-runs/20261104-three-chats/unity/InventoryItems/r2'
New-Item -ItemType Directory -Force $evidence|Out-Null
$inputs=@('scripts/weapon_rack.gd','scripts/weapon_inventory.gd','scripts/arsenal_data.gd','scripts/weapon_rarity_r6.gd','scripts/one_star0991.gd','scripts/field_consumables.gd','scripts/item_catalog_service_088.gd','assets/data/one_star_050.json','assets/data/weapon_rarity_r6.json','assets/data/one_star0991.json')
$hashes=foreach($tree in 'quest-r22/source','game'){foreach($file in $inputs){$path=Join-Path $Root "$tree/$file";@{path=$path;sha256=(Get-FileHash $path -Algorithm SHA256).Hash}}}
@{baseline='bdba6e30012e1733efd5021fd8ded593f82f26e6';inputs=$hashes;weapons=$records}|ConvertTo-Json -Depth 8|Set-Content "$evidence/source-manifest.json" -Encoding UTF8
Write-Output 'Exported 30 rack definitions (28 active), 5 item/utility definitions, 150 stat rows.'
