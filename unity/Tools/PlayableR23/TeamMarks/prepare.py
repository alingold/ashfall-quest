def render(name):
    svg=ET.parse(SOURCE/'assets/ui'/name).getroot()
    width,height=map(float,svg.attrib.get('viewBox','0 0 '+svg.attrib.get('width','64')+' '+svg.attrib.get('height','64')).split()[2:])
    factor=256/width*SCALE;im=Image.new('RGBA',(256*SCALE,round(height*factor)));draw=ImageDraw.Draw(im)
    def color(value,opacity):
        if value=='none':return None
        if value in ('white','black'):rgb=(255,255,255) if value=='white' else (0,0,0)
        else:
            if len(value)==4:value='#'+''.join(c*2 for c in value[1:])
            rgb=tuple(int(value[j:j+2],16) for j in (1,3,5))
        return rgb+(round(opacity*255),)
    def visit(el,inherited):
        style=dict(inherited);style.update(el.attrib);tag=el.tag.split('}')[-1]
        fill=color(style.get('fill','black'),float(style.get('opacity',1))*float(style.get('fill-opacity',1)))
        stroke=color(style.get('stroke','none'),float(style.get('opacity',1))*float(style.get('stroke-opacity',1)))
        thick=max(1,round(float(style.get('stroke-width',1))*factor))
        if tag=='path':
            for points,closed in paths(el.attrib['d']):
                points=[(x*factor,y*factor) for x,y in points]
                if fill and len(points)>=3:draw.polygon(points,fill=fill)
                if stroke and len(points)>1:
                    draw.line(points,fill=stroke,width=thick,joint='curve')
                    if style.get('stroke-linecap')=='round':
                        for x,y in points:draw.ellipse((x-thick/2,y-thick/2,x+thick/2,y+thick/2),fill=stroke)
        elif tag=='circle':
            x=float(style['cx'])*factor;y=float(style['cy'])*factor;r=float(style['r'])*factor
            draw.ellipse((x-r,y-r,x+r,y+r),fill=fill,outline=stroke,width=thick)
        elif tag not in ('svg','g'):raise ValueError(tag)
        for child in el:visit(child,style)
    visit(svg,{})
    path=OUT/(Path(name).stem+'.png');im.resize((256,round(height*256/width)),Image.Resampling.LANCZOS).save(path)
    return path
